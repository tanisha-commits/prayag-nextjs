import "server-only";
import dimensions from "./image-dimensions.generated.json";
import { BASE_PATH, withBasePath } from "./base-path";
import { IMAGE_WIDTHS, isOptimizable, optimizedUrl, responsiveImg, type ResponsiveImgProps } from "./optimized-image";

const table: Record<string, readonly number[] | undefined> = dimensions;

function entry(src: string | undefined | null): readonly number[] | undefined {
  if (!src) return undefined;
  let path = src.split("?")[0];
  if (BASE_PATH && path.startsWith(BASE_PATH + "/")) path = path.slice(BASE_PATH.length);
  let hit = table[path];
  if (!hit) {
    try {
      hit = table[decodeURIComponent(path)];
    } catch {
      /* malformed escape: no entry */
    }
  }
  return hit;
}

/** Natural size of a local image under /sites/prayag (generated by scripts/images/image-dimensions.mjs). */
export function imageDims(src: string | undefined | null): { width: number; height: number } | undefined {
  const hit = entry(src);
  return hit ? { width: hit[0], height: hit[1] } : undefined;
}

/** responsiveImg() with the natural size looked up from the manifest. */
export function img(src: string, sizes: string, minWidth = 0): ResponsiveImgProps {
  return responsiveImg(src, imageDims(src), sizes, minWidth);
}

/**
 * Same pixels, better encoding: the optimizer URL for this file at its own natural width (it never
 * upscales or crops), or the original when it is not a local raster, has no manifest entry or is
 * wider than the largest optimizer width. Used where the existing candidates
 * (Drupal image-style srcsets) must keep deciding the rendered size and sharpness exactly as on live.
 */
export function transcodedUrl(url: string): string {
  const dims = imageDims(url);
  const cap = IMAGE_WIDTHS[IMAGE_WIDTHS.length - 1];
  if (!dims || !isOptimizable(url) || dims.width > cap) return withBasePath(url);
  return optimizedUrl(url, IMAGE_WIDTHS.find((w) => w >= dims.width) ?? cap);
}

/** transcodedUrl() for every candidate of a srcset, descriptors unchanged. */
export function transcodedSrcSet(srcSet: string): string {
  return srcSet
    .split(",")
    .map((part) => part.replace(/^(\s*)(\S+)/, (_, ws: string, url: string) => ws + transcodedUrl(url)))
    .join(",");
}

const IMG_TAG = /<img\b[^>]*>/gi;

function attr(tag: string, name: string): string | undefined {
  const m = tag.match(new RegExp(`\\s${name}\\s*=\\s*(["'])(.*?)\\1`, "i"));
  return m ? m[2] : undefined;
}

function escapeAttr(value: string): string {
  return value.replace(/&/g, "&amp;").replace(/"/g, "&quot;");
}

/**
 * Stored HTML (category/product/FAQ/page bodies): points each local raster <img> at optimizer
 * candidates. The original `src` is replaced by a resized copy and missing width/height attributes are
 * filled with the natural size (attributes that are already present are kept, so the rendered box does
 * not change). Images that already have a `srcset` keep it, with every candidate re-encoded at the
 * same pixel size (transcodedSrcSet). Run before storedHtml().
 */
export function responsiveImagesHtml(html: string): string {
  if (!html || !html.includes("<img")) return html;
  return html.replace(IMG_TAG, (tag) => {
    const src = attr(tag, "src");
    if (!src || !isOptimizable(src)) return tag;
    // Images that already carry a srcset (Drupal image styles: banners) keep their candidates, so the
    // rendered size and sharpness stay exactly as on live; only inefficient files are re-encoded.
    const existing = attr(tag, "srcset");
    if (existing !== undefined) {
      return tag
        .replace(/\ssrcset\s*=\s*(["'])([\s\S]*?)\1/i, () => ` srcset="${escapeAttr(transcodedSrcSet(existing))}"`)
        .replace(/\ssrc\s*=\s*(["'])(.*?)\1/i, () => ` src="${escapeAttr(transcodedUrl(src))}"`);
    }
    const dims = imageDims(src);
    if (!dims) return tag;
    const lazy = /\sloading\s*=\s*["']?lazy/i.test(tag);
    const explicitWidth = Number(attr(tag, "width")) || 0;
    const fillsDims = !attr(tag, "width") && !attr(tag, "height");
    // `sizes="auto"` makes the UA apply `contain: size` with a 300×150 fallback box, so it is only safe
    // when the aspect ratio comes from numeric width AND height attributes (present or filled below).
    // Stored HTML often has percentage attributes (width="29.31%" height="100%"); those keep the plain list.
    const numericDims = fillsDims || (/^\d+$/.test(attr(tag, "width") ?? "") && /^\d+$/.test(attr(tag, "height") ?? ""));
    // Without layout knowledge: capped at a numeric width attribute; a percentage width is at most that
    // share of the viewport on desktop (theme CSS widens these images up to full width below 992px);
    // otherwise the viewport.
    const pct = /^(\d+(?:\.\d+)?)%$/.exec(attr(tag, "width") ?? "");
    const fallback = explicitWidth
      ? `(max-width: ${explicitWidth}px) 100vw, ${explicitWidth}px`
      : pct
        ? `(max-width: 991px) 100vw, ${Math.ceil(Number(pct[1]))}vw`
        : "100vw";
    const sizes = lazy && numericDims ? `auto, ${fallback}` : fallback;
    const p = responsiveImg(src, dims, sizes);
    let out = tag
      .replace(/\ssizes\s*=\s*(["'])[\s\S]*?\1/gi, "")
      .replace(/\ssrc\s*=\s*(["'])(.*?)\1/i, ` src="${escapeAttr(p.src)}" srcset="${escapeAttr(p.srcSet ?? "")}" sizes="${p.sizes}"`);
    if (fillsDims) out = out.replace(/^<img\b/i, `<img width="${dims.width}" height="${dims.height}"`);
    return out;
  });
}

/**
 * Drop-in for hand-ported `<img src={withBasePath(x)}>` tags whose rendered size is unknown here:
 * optimizer candidates with `sizes="100vw"` (never smaller than what is rendered, even for cover
 * crops) and the natural width/height (the same box as the original file: attributes the tag already
 * has are written after the spread and win). Unknown or non-raster files pass through unchanged.
 */
export function fullImg(src: string): ResponsiveImgProps {
  return img(src, "100vw");
}

/** Same for a single-URL `<source srcSet>` inside a <picture> (art-directed banners). */
export function fullSource(src: string): { srcSet: string; sizes?: string } {
  const p = img(src, "100vw");
  return p.srcSet ? { srcSet: p.srcSet, sizes: p.sizes } : { srcSet: withBasePath(src) };
}
